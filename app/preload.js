const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('bplus', {
  prepareMedia:(p,force)=>ipcRenderer.invoke('media:prepare',p,force),
  cancelPreparation:()=>ipcRenderer.invoke('media:cancel'),
  clearMediaCache:()=>ipcRenderer.invoke('media:clear-cache'),
  onPreparation:cb=>ipcRenderer.on('media:preparation',(e,info)=>cb(info)),
  pullLaunch:()=>ipcRenderer.invoke('launch:pull'),
  acknowledgeLaunch:id=>ipcRenderer.send('launch:ack',id),
  exportLaunchReport:()=>ipcRenderer.invoke('launch:export'),
  launchDiagnostics:()=>ipcRenderer.invoke('launch:diagnostics'),
  setOpacity:value=>ipcRenderer.invoke('window:opacity',value),
  setAlwaysOnTop:(flag)=>ipcRenderer.invoke('window:always-on-top',flag),
  confirmDialog:(opts)=>ipcRenderer.invoke('dialog:confirm',opts),
  trashItem:(p)=>ipcRenderer.invoke('media:trash',p),
  setUILanguage:(l)=>ipcRenderer.send('ui:language',l),
  appVersion:()=>ipcRenderer.invoke('app:version'),
  updateCheck:()=>ipcRenderer.invoke('update:check'),
  updateDownload:(info)=>ipcRenderer.invoke('update:download',info),
  updateInstall:(p)=>ipcRenderer.invoke('update:install',p),
  updatePrompt:(info)=>ipcRenderer.invoke('update:prompt',info),
  onUpdateProgress:(cb)=>ipcRenderer.on('update:progress',(e,p)=>cb(p)),
  systemTheme:()=>ipcRenderer.invoke('system:theme'),
  onTheme:cb=>ipcRenderer.on('theme:changed',(e,theme)=>cb(theme)),
  rendererReady: () => ipcRenderer.send('renderer:ready'),
  onExternalMedia: (cb) => ipcRenderer.on('media:external', (e, entries) => cb(entries)),
  entriesForPaths: (paths) => ipcRenderer.invoke('media:entries', paths),
  siblingEntries: (p) => ipcRenderer.invoke('media:siblings', p),
  openDefaults: () => ipcRenderer.invoke('system:defaults'),
  systemInfo: () => ipcRenderer.invoke('system:info'),
  openFiles: () => ipcRenderer.invoke('media:open'),
  openFolder: () => ipcRenderer.invoke('media:open-folder'),
  openSubtitleDialog: () => ipcRenderer.invoke('subtitle:open'),
  coverExtract: (p) => ipcRenderer.invoke('cover:extract', p),
  showAbout: () => ipcRenderer.invoke('app:about'),
  readSubtitle: (p) => ipcRenderer.invoke('subtitle:read', p),
  autoSubtitle: (videoPath) => ipcRenderer.invoke('subtitle:auto', videoPath),
  pathForFile: (f) => webUtils.getPathForFile(f),
  saveSnapshot: (dataUrl) => ipcRenderer.invoke('snapshot:save', dataUrl),
  onSnapshotSaved: (cb) => ipcRenderer.on('snapshot:saved', (e, name) => cb(name)),
  winMin: () => ipcRenderer.send('win:min'),
  winMaxToggle: () => ipcRenderer.send('win:max-toggle'),
  winClose: () => ipcRenderer.send('win:close'),
  onMenuAction: (cb) => ipcRenderer.on('menu:action', (e, a) => cb(a)),
  onPlaylistAdd: (cb) => ipcRenderer.on('playlist:add', (e, entries) => cb(entries)),
  onSubtitleLoad: (cb) => ipcRenderer.on('subtitle:load', (e, s) => cb(s)),
  onTestRun: (cb) => ipcRenderer.on('test:run', (e, entries) => cb(entries)),
  sendTestResult: (r) => ipcRenderer.send('test:result', r)
});
